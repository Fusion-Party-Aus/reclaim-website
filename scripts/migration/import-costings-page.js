const costingsPage = {
  _type: 'page',
  title: "We've Done the Maths",
  slug: { _type: 'slug', current: 'costings' },
  subtitle: 'Sane financial policies for a wealthier Victoria.',
  metaDescription: 'Read the costings, economic rationale, and funding plan for the Fusion Victoria platform.',
  showSidebar: true,
  pageType: 'standard',
  body: costingsBlocks
}

async function run() {
  try {
    // 1. Delete the /policy-omnibus page if it exists to clean up
    console.log('Checking for old "policy-omnibus" page to clean up...')
    const oldOmnibus = await client.fetch(
      '*[_type == "page" && slug.current == "policy-omnibus"][0]'
    )
    if (oldOmnibus) {
      console.log(`  Deleting page: ${oldOmnibus._id}`)
      await client.delete(oldOmnibus._id)
      console.log('  ✅ Deleted.')
    }

    // 2. Upsert the costings page
    console.log('Checking if costings page already exists in Sanity...')
    const existing = await client.fetch(
      '*[_type == "page" && slug.current == "costings"][0]'
    )

    if (existing) {
      console.log(`  ⚠️  Page already exists (ID: ${existing._id}). Updating content...`)
      const result = await client
        .patch(existing._id)
        .set({
          title: costingsPage.title,
          subtitle: costingsPage.subtitle,
          metaDescription: costingsPage.metaDescription,
          showSidebar: costingsPage.showSidebar,
          pageType: costingsPage.pageType,
          body: costingsPage.body
        })
        .commit()
      console.log(`  ✅ Updated: ${result._id}`)
    } else {
      console.log('  Creating new costings page...')
      const result = await client.create(costingsPage)
      console.log(`  ✅ Created: ${result._id}`)
    }
  } catch (error) {
    console.error('  ❌ Error in migration:', error.message)
    process.exit(1)
  }

  console.log('\n✨ Costings page import complete!')
}

run().catch((err) => {
  console.error('Fatal error:', err)
  process.exit(1)
})
